import { execFile } from "node:child_process";
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { promisify } from "node:util";
import { AdminError, HttpError } from "./errors.js";
import { run } from "./jobs.js";

// The ordering rule shared with the site's build (src/utils/loadImages.js).
const require = createRequire(import.meta.url);
const { ORDER_FILE, splitName, isImageFile, parseOrder, listImages, orderGallery, orderCarousel } =
  require("../../src/utils/imageOrder.js");
const sidebarRules = require("../../src/utils/sidebar.js");

export { isImageFile };
export const GALLERY_DIR = "public/gallery";
export const CAROUSEL_DIR = "public/carousel";
export const SIDEBAR_DIR = sidebarRules.SIDEBAR_DIR;
const SIDEBAR_FILE = sidebarRules.CONTENT_FILE;
// Generated by `yarn build-images`; committed with the originals.
const MANIFESTS = ["src/gallery.json", "src/carousel.json", "src/sidebar.json", "src/work-gallery.json"];
// What the admin edits; Save stages exactly these.
const CONTENT_PATHS = [GALLERY_DIR, CAROUSEL_DIR, SIDEBAR_DIR, ORDER_FILE, SIDEBAR_FILE, ...MANIFESTS];
// Files that may not exist (never committed, never created).
const OPTIONAL_PATHS = [ORDER_FILE, SIDEBAR_DIR];
const MAX_HEADING = 200;
const MAX_DESCRIPTION = 20000;

// Git never prompts (a missing credential fails instead of hanging), never
// opens an editor, and read-only commands such as the status refresh behind
// /api/state never take index.lock away from a running job.
const GIT_ENV = { GIT_TERMINAL_PROMPT: "0", GIT_EDITOR: "true", GIT_SEQUENCE_EDITOR: "true", GIT_OPTIONAL_LOCKS: "0" };
// Network steps get a shorter leash than builds.
const NETWORK_TIMEOUT = 5 * 60 * 1000;
const execFileAsync = promisify(execFile);

export async function git(cwd, args) {
  const { stdout } = await execFileAsync("git", args, {
    cwd,
    env: { ...process.env, ...GIT_ENV },
    maxBuffer: 64 * 1024 * 1024,
    timeout: 2 * 60 * 1000, // local, read-mostly commands; network steps use run()
  });
  return stdout;
}

async function gitOk(cwd, args) {
  return git(cwd, args).then(() => true, () => false);
}

// Names the step a job is on, for its progress line ("step.<code>" in
// public/i18n/). Tests pass a plain log function.
const step = (log, code, params) => log.step?.(code, params);

function runGit(cwd, args, log, options = {}) {
  return run("git", args, { cwd, log, env: GIT_ENV, ...options });
}

export class Workspace {
  constructor(config) {
    this.root = config.workspace;
    this.config = config;
    this.deployedFile = path.join(config.stateDir, "deployed.json");
    // Present while the admin's own rebase runs (see recover()).
    this.rebaseMarker = path.join(config.stateDir, "rebasing");
  }

  file(...parts) {
    return path.join(this.root, ...parts);
  }

  // ---- Reading -----------------------------------------------------------

  // duringJob: a running deploy may be in the middle of its own rebase.
  // allowRebase: Discard, which aborts one.
  async check({ duringJob = false, allowRebase = false } = {}) {
    if (!fs.existsSync(this.file(".git"))) throw new AdminError("not-a-clone", { path: this.root });
    if (duringJob) return;
    if (await this.rebaseInProgress()) {
      if (allowRebase) return;
      throw new HttpError(409, "rebase-in-progress");
    }
    const branch = (await git(this.root, ["symbolic-ref", "--quiet", "--short", "HEAD"]).catch(() => "")).trim();
    if (branch !== this.config.branch) {
      throw new HttpError(409, branch ? "wrong-branch" : "detached-head", { branch, expected: this.config.branch });
    }
  }

  // At startup, before anything holds the lock: a rebase the admin started
  // (the marker is there) was interrupted by the restart, so abort it. One
  // started by hand is left alone.
  async recover() {
    try {
      if (fs.existsSync(this.rebaseMarker) && fs.existsSync(this.file(".git")) && (await this.rebaseInProgress())) {
        console.log("Aborting a rebase interrupted by a restart");
        await git(this.root, ["rebase", "--abort"]);
      }
      fs.rmSync(this.rebaseMarker, { force: true });
    } catch (error) {
      console.error("Couldn't abort the interrupted rebase:", error.message);
    }
  }

  async tree() {
    return (await git(this.root, ["rev-parse", "HEAD^{tree}"])).trim();
  }

  async rebaseInProgress() {
    for (const name of ["rebase-merge", "rebase-apply"]) {
      const dir = (await git(this.root, ["rev-parse", "--git-path", name])).trim();
      if (fs.existsSync(path.resolve(this.root, dir))) return true;
    }
    return false;
  }

  readOrder() {
    const file = this.file(ORDER_FILE);
    return fs.existsSync(file) ? readable(ORDER_FILE, () => parseOrder(fs.readFileSync(file, "utf-8"))) : {};
  }

  // The draft as the build will see it.
  current() {
    const order = this.readOrder();
    const gallery = orderGallery(listImages(this.file(GALLERY_DIR)), order.gallery);
    const carouselFiles = listImages(this.file(CAROUSEL_DIR));
    return { order, gallery, carouselFiles, carousel: orderCarousel(carouselFiles, gallery, order.carousel) };
  }

  // The same, as committed in HEAD.
  async committed() {
    const images = async (dir) =>
      (await git(this.root, ["ls-tree", "-z", "HEAD", "--", `${dir}/`]))
        .split("\0")
        .filter(Boolean)
        .map((entry) => entry.split("\t"))
        .filter(([meta, file]) => meta.split(" ")[1] === "blob" && isImageFile(path.basename(file)))
        .map(([, file]) => path.basename(file))
        .sort();
    const order = await git(this.root, ["show", `HEAD:${ORDER_FILE}`]).then(parseOrder, () => ({}));
    const gallery = orderGallery(await images(GALLERY_DIR), order.gallery);
    const sidebar = await git(this.root, ["show", `HEAD:${SIDEBAR_FILE}`])
      .then((text) => sidebarRules.validateContent(JSON.parse(text)))
      .catch(() => sidebarRules.validateContent({ entries: [] }));
    return { gallery, carousel: orderCarousel(await images(CAROUSEL_DIR), gallery, order.carousel), sidebar };
  }

  // git status entries: [{ code, file }]
  async status() {
    const out = await git(this.root, ["status", "--porcelain=v1", "-z", "--untracked-files=all"]);
    const entries = [];
    const parts = out.split("\0");
    for (let i = 0; i < parts.length; i++) {
      if (!parts[i]) continue;
      const code = parts[i].slice(0, 2);
      entries.push({ code, file: parts[i].slice(3) });
      if (code[0] === "R" || code[0] === "C") i++; // the rename source follows
    }
    return entries;
  }

  async draft() {
    const [head, status] = await Promise.all([this.committed(), this.status()]);
    const now = { ...this.current(), sidebar: this.readSidebar() };
    const isContent = (file) => CONTENT_PATHS.some((p) => file === p || file.startsWith(`${p}/`));
    return {
      ...describeChanges(head, now),
      dirty: status.length > 0,
      other: status.filter(({ file }) => !isContent(file)).map(({ code, file }) => `${code} ${file}`),
    };
  }

  readDeployed() {
    try {
      return JSON.parse(fs.readFileSync(this.deployedFile, "utf-8"));
    } catch {
      return null;
    }
  }

  async commits(range) {
    const out = await git(this.root, ["log", "--format=%H%x00%s%x00%cI", range, "--"]).catch(() => "");
    return out.split("\n").filter(Boolean).map((line) => {
      const [sha, subject, date] = line.split("\0");
      return { sha, subject, date };
    });
  }

  async history() {
    const { remote, branch } = this.config;
    const upstream = `${remote}/${branch}`;
    const head = (await git(this.root, ["rev-parse", "HEAD"])).trim();
    const hasUpstream = await gitOk(this.root, ["rev-parse", "--verify", "--quiet", `refs/remotes/${upstream}`]);
    let deployed = this.readDeployed();
    if (deployed && !(await gitOk(this.root, ["merge-base", "--is-ancestor", deployed.sha, "HEAD"]))) {
      deployed = { ...deployed, diverged: true };
    }
    const base = deployed && !deployed.diverged ? deployed.sha : hasUpstream ? upstream : null;
    return {
      head,
      deployed,
      // Saved but not live: commits since the last deploy from this admin (or,
      // before the first one, since origin/main).
      notDeployed: base ? await this.commits(`${base}..HEAD`) : [],
      // null: since the last deploy.
      notDeployedBase: deployed && !deployed.diverged ? null : upstream,
      notPushed: hasUpstream ? (await this.commits(`${upstream}..HEAD`)).length : null,
      behind: hasUpstream ? (await this.commits(`HEAD..${upstream}`)).length : null,
    };
  }

  // ---- Draft edits (callers hold the lock) -------------------------------

  writeOrder(order) {
    const file = this.file(ORDER_FILE);
    const temp = `${file}.tmp`;
    fs.writeFileSync(temp, `${JSON.stringify(order, null, 2)}\n`, "utf-8");
    fs.renameSync(temp, file);
  }

  // gallery: every gallery file, in the new order. carousel: the slides.
  setOrder({ gallery, carousel }) {
    const now = this.current();
    if (!Array.isArray(gallery) || !Array.isArray(carousel)) throw new HttpError(400, "order-invalid");
    if (gallery.length !== now.gallery.length || new Set(gallery).size !== gallery.length || !gallery.every((file) => now.gallery.includes(file))) {
      throw new HttpError(409, "gallery-changed");
    }
    const candidates = new Set([...now.carouselFiles.map((f) => `carousel/${f}`), ...now.gallery.map((f) => `gallery/${f}`)]);
    if (new Set(carousel).size !== carousel.length || !carousel.every((ref) => candidates.has(ref))) {
      throw new HttpError(400, "unknown-slide");
    }
    this.writeOrder({ ...now.order, gallery, carousel });
  }

  // uploads: [{ path, stem, extension }] validated temp files. They go to the
  // front of the gallery, in the given order. Returns the new file names.
  addUploads(uploads) {
    const dir = this.file(GALLERY_DIR);
    const now = this.current();
    const taken = new Set(fs.readdirSync(dir).map((entry) => splitName(entry).name.toLowerCase()));
    const names = uploads.map(({ stem, extension }) => {
      let name = stem;
      for (let n = 2; taken.has(name.toLowerCase()); n++) name = `${stem}-${n}`;
      taken.add(name.toLowerCase());
      return `${name}.${extension}`;
    });
    const copied = [];
    try {
      uploads.forEach((upload, i) => {
        fs.copyFileSync(upload.path, path.join(dir, names[i]), fs.constants.COPYFILE_EXCL);
        copied.push(path.join(dir, names[i]));
      });
    } catch (error) {
      copied.forEach((file) => fs.rmSync(file, { force: true }));
      throw error;
    }
    this.writeOrder({ ...now.order, gallery: [...names, ...now.gallery] });
    return names;
  }

  // Only an upload that was never saved (not in HEAD) can be removed.
  async removeUpload(file) {
    const { added } = describeChanges(await this.committed(), { ...this.current(), sidebar: this.readSidebar() });
    if (typeof file !== "string" || !added.includes(file)) throw new HttpError(400, "unsaved-only");
    const now = this.current();
    fs.unlinkSync(this.file(GALLERY_DIR, file));
    const order = { ...now.order, gallery: now.gallery.filter((f) => f !== file) };
    if (order.carousel) order.carousel = order.carousel.filter((ref) => ref !== `gallery/${file}`);
    this.writeOrder(order);
  }

  // ---- Sidebar entries (callers hold the lock) ---------------------------

  readSidebar() {
    return readable(SIDEBAR_FILE, () => sidebarRules.readContent(this.root));
  }

  writeSidebar(content) {
    sidebarRules.validateContent(content);
    const file = this.file(SIDEBAR_FILE);
    fs.writeFileSync(`${file}.tmp`, `${JSON.stringify(content, null, 2)}\n`, "utf-8");
    fs.renameSync(`${file}.tmp`, file);
  }

  // heading: { ja, en }; order: every entry id, in the new order.
  setSidebar({ heading, order }) {
    const content = this.readSidebar();
    const ids = content.entries.map((entry) => entry.id);
    if (!Array.isArray(order) || order.length !== ids.length || new Set(order).size !== ids.length || !order.every((id) => ids.includes(id))) {
      throw new HttpError(409, "sidebar-changed");
    }
    this.writeSidebar({
      heading: { ja: cleanHeading(heading?.ja), en: cleanHeading(heading?.en) },
      entries: order.map((id) => content.entries.find((entry) => entry.id === id)),
    });
  }

  // entry: { id?, link, description: { ja, en } }. Without an id it is a new
  // entry at the top, and needs an image. image: a validated temp upload.
  saveSidebarEntry(entry, image) {
    const content = this.readSidebar();
    const link = typeof entry?.link === "string" && entry.link.trim() ? entry.link.trim() : null;
    if (link !== null && !sidebarRules.isValidLink(link)) throw new HttpError(400, "invalid-link");
    const description = { ja: cleanDescription(entry?.description?.ja), en: cleanDescription(entry?.description?.en) };
    const existing = entry?.id === undefined ? null : content.entries.find((e) => e.id === entry.id);
    if (entry?.id !== undefined && !existing) throw new HttpError(409, "entry-gone");
    if (!existing && !image) throw new HttpError(400, "entry-needs-image");

    let imagePath = existing?.image;
    if (image) {
      const dir = this.file(SIDEBAR_DIR);
      fs.mkdirSync(dir, { recursive: true });
      const taken = new Set(fs.readdirSync(dir).map((name) => path.parse(name).name.toLowerCase()));
      let stem = image.stem;
      for (let n = 2; taken.has(stem.toLowerCase()); n++) stem = `${image.stem}-${n}`;
      fs.copyFileSync(image.path, path.join(dir, `${stem}.${image.extension}`), fs.constants.COPYFILE_EXCL);
      imagePath = `sidebar/${stem}.${image.extension}`;
    }
    const ids = new Set(content.entries.map((e) => e.id));
    const base = path.parse(imagePath).name; // a sanitized stem
    let id = existing?.id ?? base;
    for (let n = 2; !existing && ids.has(id); n++) id = `${base}-${n}`;

    const saved = { id, image: imagePath, link, description };
    const entries = existing ? content.entries.map((e) => (e.id === id ? saved : e)) : [saved, ...content.entries];
    this.writeSidebar({ ...content, entries });
    if (existing && existing.image !== imagePath) this.dropSidebarImage(existing.image, entries);
    return saved;
  }

  removeSidebarEntry(id) {
    const content = this.readSidebar();
    const entry = content.entries.find((e) => e.id === id);
    if (!entry) throw new HttpError(409, "entry-gone");
    const entries = content.entries.filter((e) => e !== entry);
    this.writeSidebar({ ...content, entries });
    this.dropSidebarImage(entry.image, entries);
  }

  // Deletes an image from public/sidebar/ once no entry uses it (a committed
  // one stays in the git history). Images elsewhere in public/ are kept.
  dropSidebarImage(image, entries) {
    if (!image.startsWith("sidebar/") || entries.some((e) => e.image === image)) return;
    fs.rmSync(this.file("public", image), { force: true });
  }

  async discard() {
    if (await this.rebaseInProgress()) await git(this.root, ["rebase", "--abort"]);
    await git(this.root, ["reset", "--hard", "--quiet", "HEAD"]);
    // Untracked files only; ignored ones (node_modules, build, derivatives) stay.
    await git(this.root, ["clean", "-d", "--force", "--quiet"]);
  }

  // ---- Jobs (callers hold the lock) --------------------------------------

  async install(log) {
    step(log, "install");
    await run("yarn", ["install", "--frozen-lockfile", "--non-interactive", "--prefer-offline"], { cwd: this.root, log });
  }

  async buildImages(log) {
    step(log, "images");
    await run("yarn", ["build-images"], { cwd: this.root, log });
  }

  async preview(log, outDir) {
    await this.install(log);
    await this.buildImages(log);
    step(log, "build");
    await run(this.file("node_modules/.bin/vite"), ["build", "--outDir", outDir, "--emptyOutDir"], { cwd: this.root, log });
  }

  async save(log, message) {
    await this.install(log);
    await this.buildImages(log);
    await this.commitContent(log, message, () => {
      throw new AdminError("nothing-to-save");
    });
    const sha = (await git(this.root, ["rev-parse", "--short", "HEAD"])).trim();
    log(`✓ Saved as ${sha}`);
    return { sha };
  }

  // Stages and commits the content paths, and only them: anything else that
  // happens to be in the index stays out of the commit.
  async commitContent(log, message, onNothing = () => {}) {
    // A pathspec matching nothing (never created, never committed) is an error.
    const paths = [];
    for (const p of CONTENT_PATHS) {
      if (fs.existsSync(this.file(p)) || (OPTIONAL_PATHS.includes(p) && (await gitOk(this.root, ["ls-files", "--error-unmatch", "--", p])))) paths.push(p);
    }
    await runGit(this.root, ["add", "--all", "--", ...paths], log);
    // The commit's pathspecs must be known to git, now or in HEAD (a deletion):
    // build-images creates public/sidebar/ for its ignored large/ alone.
    const known = [];
    for (const p of paths) {
      if ((await git(this.root, ["ls-files", "--", p])).trim() || (await git(this.root, ["ls-tree", "--name-only", "HEAD", "--", p])).trim()) known.push(p);
    }
    if (!known.length || (await gitOk(this.root, ["diff", "--cached", "--quiet", "--", ...known]))) return onNothing();
    step(log, "commit");
    await runGit(this.root, ["commit", "--quiet", "-m", message, "--only", "--", ...known], log);
  }

  async deploy(log) {
    const { remote, branch, deployCommand } = this.config;
    const upstream = `${remote}/${branch}`;
    const status = await this.status();
    if (status.length) {
      const files = `${status.slice(0, 5).map((e) => e.file).join(", ")}${status.length > 5 ? ", …" : ""}`;
      throw new AdminError("unsaved-changes", { files });
    }

    log("== Fetching");
    step(log, "fetch");
    await runGit(this.root, ["fetch", "--quiet", remote, branch], log, { timeoutMs: NETWORK_TIMEOUT });
    if (!(await gitOk(this.root, ["merge-base", "--is-ancestor", upstream, "HEAD"]))) {
      log(`== Rebasing the saved commits onto ${upstream}`);
      step(log, "rebase", { upstream });
      await this.rebase(upstream, log);
    }

    // Every time, not only after a rebase in this run: a rebase whose deploy
    // failed later leaves manifests from the conflict resolution behind.
    // Nothing is committed when they are already right.
    await this.install(log);
    log("== Regenerating the manifests");
    await this.buildImages(log);
    await this.commitContent(log, "content: regenerate image manifests");

    const head = (await git(this.root, ["rev-parse", "HEAD"])).trim();
    if (head !== (await git(this.root, ["rev-parse", upstream])).trim()) {
      log(`== Pushing ${branch}`);
      step(log, "push");
      try {
        await runGit(this.root, ["push", "--porcelain", remote, `HEAD:refs/heads/${branch}`], log, { timeoutMs: NETWORK_TIMEOUT });
      } catch {
        throw new AdminError("push-failed");
      }
    } else {
      log("== Nothing new to push");
    }

    log(`== Deploying: ${deployCommand.join(" ")}`);
    step(log, "deploy");
    await run(deployCommand[0], deployCommand.slice(1), { cwd: this.root, log });

    const subject = (await git(this.root, ["log", "-1", "--format=%s", head])).trim();
    const deployed = { sha: head, subject, at: new Date().toISOString() };
    fs.writeFileSync(this.deployedFile, `${JSON.stringify(deployed, null, 2)}\n`);
    log(`✓ Deployed ${head.slice(0, 7)} (${subject})`);
    return deployed;
  }

  // Conflicts in the generated manifests alone are expected (every Save
  // commits them) and resolved with main's version, since the deploy
  // regenerates them right after. Any other conflict aborts the rebase.
  async rebase(upstream, log) {
    fs.writeFileSync(this.rebaseMarker, upstream);
    try {
      let args = ["rebase", upstream];
      for (;;) {
        try {
          return await runGit(this.root, args, log);
        } catch {
          // Throws (and so aborts) unless the stop is only about manifests.
          const empty = await this.resolveManifestConflicts(log);
          args = ["rebase", empty ? "--skip" : "--continue"];
        }
      }
    } catch (error) {
      await runGit(this.root, ["rebase", "--abort"], log).catch(() => {});
      // Both messages say nothing was pushed or deployed.
      throw error.code === "rebase-conflict" ? error : new AdminError("rebase-failed");
    } finally {
      fs.rmSync(this.rebaseMarker, { force: true });
    }
  }

  // Resolves a rebase stop that is only about generated manifests, and says
  // whether the commit became empty. Throws for anything else.
  async resolveManifestConflicts(log) {
    const conflicts = (await git(this.root, ["diff", "--name-only", "--diff-filter=U"]).catch(() => "")).trim().split("\n").filter(Boolean);
    if (!conflicts.length || !conflicts.every((file) => MANIFESTS.includes(file))) {
      throw conflicts.length ? new AdminError("rebase-conflict", { files: conflicts.join(", ") }) : new AdminError("rebase-failed");
    }
    log(`Conflict only in generated manifests (${conflicts.join(", ")}): taking main's version, they are regenerated next`);
    for (const file of conflicts) {
      // During a rebase "ours" is the branch being rebased onto; main may
      // also have deleted the file.
      const onMain = await gitOk(this.root, ["cat-file", "-e", `HEAD:${file}`]);
      if (onMain) await runGit(this.root, ["checkout", "--ours", "--", file], log);
      await runGit(this.root, onMain ? ["add", "--", file] : ["rm", "--quiet", "--force", "--", file], log);
    }
    return gitOk(this.root, ["diff", "--cached", "--quiet"]);
  }
}

// What a draft changes, for the UI and the commit message.
export function describeChanges(head, now) {
  const added = now.gallery.filter((f) => !head.gallery.includes(f));
  const removed = head.gallery.filter((f) => !now.gallery.includes(f));
  const slidesAdded = now.carousel.filter((r) => !head.carousel.includes(r));
  const slidesRemoved = head.carousel.filter((r) => !now.carousel.includes(r));
  const sameOrder = (a, b) => {
    const common = a.filter((x) => b.includes(x));
    return common.join("\0") === b.filter((x) => a.includes(x)).join("\0");
  };
  // Prepending uploads is not a reorder; moving existing pictures is.
  const reordered = !sameOrder(head.gallery, now.gallery);
  const carouselReordered = !sameOrder(head.carousel, now.carousel);
  const ids = (sidebar) => sidebar.entries.map((entry) => entry.id);
  const headIds = ids(head.sidebar);
  const nowIds = ids(now.sidebar);
  const entry = (sidebar, id) => JSON.stringify(sidebar.entries.find((e) => e.id === id));
  return {
    added,
    removed,
    reordered,
    slidesAdded,
    slidesRemoved,
    carouselReordered,
    entriesAdded: nowIds.filter((id) => !headIds.includes(id)),
    entriesRemoved: headIds.filter((id) => !nowIds.includes(id)),
    entriesEdited: nowIds.filter((id) => headIds.includes(id) && entry(head.sidebar, id) !== entry(now.sidebar, id)),
    entriesReordered: !sameOrder(headIds, nowIds),
    headingChanged: JSON.stringify(head.sidebar.heading) !== JSON.stringify(now.sidebar.heading),
  };
}

export function commitMessage(changes) {
  const { added, removed, reordered, slidesAdded, slidesRemoved, carouselReordered } = changes;
  const { entriesAdded, entriesRemoved, entriesEdited, entriesReordered, headingChanged } = changes;
  const plural = (n, word) => `${n} ${word}${n === 1 ? "" : "s"}`;
  const subject = [
    added.length && `add ${plural(added.length, "illustration")}`,
    removed.length && `remove ${plural(removed.length, "illustration")}`,
    reordered && "reorder the gallery",
    (slidesAdded.length || slidesRemoved.length || carouselReordered) && "update the carousel",
    (entriesAdded.length || entriesRemoved.length || entriesEdited.length || entriesReordered || headingChanged) && "update the sidebar",
  ].filter(Boolean);
  const body = [
    ...(added.length ? ["Added to the gallery:", ...added.map((f) => `- ${f}`)] : []),
    ...(removed.length ? ["Removed from the gallery:", ...removed.map((f) => `- ${f}`)] : []),
    ...(reordered ? ["Gallery order changed."] : []),
    ...(slidesAdded.length ? ["Carousel slides added:", ...slidesAdded.map((r) => `- ${r}`)] : []),
    ...(slidesRemoved.length ? ["Carousel slides removed:", ...slidesRemoved.map((r) => `- ${r}`)] : []),
    ...(carouselReordered ? ["Carousel order changed."] : []),
    ...(entriesAdded.length ? ["Sidebar entries added:", ...entriesAdded.map((id) => `- ${id}`)] : []),
    ...(entriesEdited.length ? ["Sidebar entries edited:", ...entriesEdited.map((id) => `- ${id}`)] : []),
    ...(entriesRemoved.length ? ["Sidebar entries removed:", ...entriesRemoved.map((id) => `- ${id}`)] : []),
    ...(entriesReordered ? ["Sidebar order changed."] : []),
    ...(headingChanged ? ["Sidebar heading changed."] : []),
  ];
  return `content: ${subject.length ? subject.join(", ") : "update the image manifests"}${body.length ? `\n\n${body.join("\n")}` : ""}\n`;
}

// A content file that doesn't parse (edited by hand, say): its code names the
// file, the parser's own text is the detail.
function readable(file, read) {
  try {
    return read();
  } catch (error) {
    throw new AdminError("content-unreadable", { file, detail: error.message.replace(`${file}: `, "") });
  }
}

function cleanHeading(text) {
  if (typeof text !== "string" || text.length > MAX_HEADING) throw new HttpError(400, "heading-too-long", { max: MAX_HEADING });
  return text.replace(/\s+/g, " ").trim();
}

function cleanDescription(text) {
  if (text === undefined) return "";
  if (typeof text !== "string" || text.length > MAX_DESCRIPTION) throw new HttpError(400, "description-too-long", { max: MAX_DESCRIPTION });
  return text.replace(/\r\n?/g, "\n");
}
